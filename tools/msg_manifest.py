#!/usr/bin/env python3
"""The message manifest's tables and locks (B3 / B6 of 0.7.15, BUG-1136 / BUG-1137; docs/04-netcode.md#netcode-manifest).

  msg_manifest.py check        (make test) the message tables of docs/04-netcode.md are what messages.def and
                               space_kinds.def say, and every message family's wire lock holds: a family whose rows
                               (id, name, channel, direction) or wire files changed needs a bumped rev or minor
  msg_manifest.py docs         writes the tables into docs/04-netcode.md (between the manifest markers)
  msg_manifest.py lock         writes mods/coop/net/messages.lock after a bump; refuses a changed family whose rev and
                               minor are still those of the lock
  msg_manifest.py lock --rebase FAMILY "reason"
                               a change that keeps the bytes on the wire (a refactoring whose golden-byte tests pass):
                               the family's hash is taken again without a bump, the reason goes into the lock file
  msg_manifest.py --self-test  the checks on a scratch copy (a changed row without a bump fails, with one passes)

rev: older versions can NOT read the family's messages any more (a peer of another rev is refused when the stage uses
the family, net/compat.h); minor: older versions still read them (a trailing field, a new type they ignore).
"""
import hashlib
import os
import re
import shutil
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NET = 'mods/coop/net'
DOCS = 'docs/04-netcode.md'
LOCK = f'{NET}/messages.lock'
BEGIN, END = '<!-- manifest tables: generated by tools/msg_manifest.py docs, do not edit -->', '<!-- end of manifest tables -->'

MSG_RE = re.compile(r'^MSG\((\d+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*"(.*)"\)\s*$')
FAM_RE = re.compile(r'^FAMILY\((\w+),\s*(\d+),\s*(\d+),\s*(\d+),\s*([^,]+),\s*"([^"]*)",\s*"([^"]*)"\)\s*$')
KIND_RE = re.compile(r'^KIND\((\d+),\s*(\w+),\s*(\w+),\s*(\w+)\)\s*$')
FEAT_RE = re.compile(r'^FEATURE\((\w+),\s*(\d+),\s*(\d+)\)\s*(//\s*(.*))?$')
STAGES = {'STAGE_ALWAYS': 'every stage and the menus', 'STAGE_CELL': 'Cell', 'STAGE_CREATURE': 'Creature',
          'STAGE_TRIBE': 'Tribe', 'STAGE_CIV': 'Civilization', 'STAGE_SPACE': 'Space'}
SENDER = {'Host': 'host', 'Guest': 'guest', 'Any': 'any'}


def read(root, rel):
    with open(os.path.join(root, rel), encoding='utf-8') as f:
        return f.read()


def parse(root):
    msgs, fams, kinds, feats, bad = [], [], [], [], []
    for ln in read(root, f'{NET}/messages.def').splitlines():
        if ln.startswith('MSG('):
            m = MSG_RE.match(ln)
            if not m:
                bad.append(f'messages.def: cannot read {ln!r}')
                continue
            msgs.append(dict(id=int(m[1]), name=m[2], chan=m[3], dir=m[4], cls=m[5], route=m[6], recv=m[7],
                             family=m[8], what=m[9]))
        elif ln.startswith('FAMILY('):
            m = FAM_RE.match(ln)
            if not m:
                bad.append(f'messages.def: cannot read {ln!r}')
                continue
            fams.append(dict(name=m[1], id=int(m[2]), rev=int(m[3]), minor=int(m[4]),
                             stages=[s.strip() for s in m[5].split('|')], title=m[6], files=m[7].split()))
    for ln in read(root, f'{NET}/space_kinds.def').splitlines():
        if ln.startswith('KIND('):
            m = KIND_RE.match(ln)
            if not m:
                bad.append(f'space_kinds.def: cannot read {ln!r}')
                continue
            kinds.append(dict(id=int(m[1]), feature=m[2], name=m[3], dir=m[4]))
        elif ln.startswith('FEATURE('):
            m = FEAT_RE.match(ln)
            if not m:
                bad.append(f'space_kinds.def: cannot read {ln!r}')
                continue
            feats.append(dict(name=m[1], lo=int(m[2]), hi=int(m[3]), what=(m[5] or '').strip()))
    for what, rows, key in (('type id', msgs, 'id'), ('type name', msgs, 'name'), ('family id', fams, 'id'),
                            ('family name', fams, 'name'), ('space kind', kinds, 'id'), ('feature', feats, 'name')):
        seen = set()
        for r in rows:
            if r[key] in seen:
                bad.append(f'duplicate {what} {r[key]}')
            seen.add(r[key])
    names = {f['name'] for f in fams}
    for m in msgs:
        if m['family'] not in names:
            bad.append(f'MSG_{m["name"]}: no family {m["family"]}')
        if m['dir'] not in SENDER:
            bad.append(f'MSG_{m["name"]}: direction {m["dir"]}')
    for f in fams:
        for s in f['stages']:
            if s not in STAGES:
                bad.append(f'family {f["name"]}: stage {s}')
    for k in kinds:
        if k['feature'] not in {f['name'] for f in feats}:
            bad.append(f'space kind {k["id"]}: no feature {k["feature"]}')
    return msgs, fams, kinds, feats, bad


def strip_code(text):
    """the code of a source without comments and blank space (a comment edit is no wire change)"""
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    text = re.sub(r'//[^\n]*', ' ', text)
    return re.sub(r'\s+', ' ', text).strip()


def family_hash(root, fam, msgs, kinds, feats):
    h = hashlib.sha256()
    for m in msgs:
        if m['family'] == fam['name']:
            h.update(f'MSG {m["id"]} {m["name"]} {m["chan"]} {m["dir"]}\n'.encode())
    if fam['name'] == 'space':  # MSG_SPACE's sub-kinds are the space family's wire
        for f in feats:
            h.update(f'FEATURE {f["name"]} {f["lo"]} {f["hi"]}\n'.encode())
        for k in kinds:
            h.update(f'KIND {k["id"]} {k["feature"]} {k["name"]} {k["dir"]}\n'.encode())
    for rel in fam['files']:
        path = os.path.join(root, 'mods/coop', rel)
        h.update(f'FILE {rel}\n'.encode())
        h.update(strip_code(open(path, encoding='utf-8').read()).encode() if os.path.exists(path) else b'(missing)')
    return h.hexdigest()[:16]


def read_lock(root):
    out = {}
    path = os.path.join(root, LOCK)
    if not os.path.exists(path):
        return out
    for ln in open(path, encoding='utf-8'):
        p = ln.split()
        if len(p) == 4 and not ln.startswith('#'):
            out[p[0]] = (int(p[1]), int(p[2]), p[3])
    return out


def write_lock(root, fams, hashes, notes):
    path = os.path.join(root, LOCK)
    old = [ln.rstrip('\n') for ln in open(path, encoding='utf-8')] if os.path.exists(path) else []
    keep = [ln for ln in old if ln.startswith('# rebased ')]
    lines = ['# The wire lock of each message family (B6 of 0.7.15, BUG-1137): family rev minor hash. Written by',
             '# tools/msg_manifest.py lock after a bump; `make test` (msg_manifest.py check) fails when a family\'s rows',
             '# or wire files changed and its rev / minor in net/messages.def did not.']
    lines += [f'{f["name"]} {f["rev"]} {f["minor"]} {hashes[f["name"]]}' for f in fams]
    lines += keep + notes
    open(path, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')


def lock_problems(root, parsed=None):
    msgs, fams, kinds, feats, bad = parsed or parse(root)
    lock = read_lock(root)
    probs = list(bad)
    hashes = {f['name']: family_hash(root, f, msgs, kinds, feats) for f in fams}
    for f in fams:
        n, cur = f['name'], (f['rev'], f['minor'])
        if n not in lock:
            probs.append(f'family {n}: not in {LOCK} (run tools/msg_manifest.py lock)')
            continue
        rev, minor, h = lock[n]
        if cur == (rev, minor) and h != hashes[n]:
            probs.append(f'family {n}: its wire changed (its rows in messages.def{" / space_kinds.def" if n == "space" else ""}'
                         f'{" or " + ", ".join(f["files"]) if f["files"] else ""}) but rev {rev} minor {minor} did not: bump '
                         f'its minor (older versions still read it) or its rev (they cannot) in net/messages.def, then run '
                         f'tools/msg_manifest.py lock (or `lock --rebase {n} "<why the bytes are the same>"`)')
        elif cur < (rev, minor):
            probs.append(f'family {n}: rev {f["rev"]}.{f["minor"]} is below the lock\'s {rev}.{minor}')
        elif cur != (rev, minor):
            probs.append(f'family {n}: bumped to {f["rev"]}.{f["minor"]}: run tools/msg_manifest.py lock')
    for n in lock:
        if n not in hashes:
            probs.append(f'family {n}: in {LOCK} but not in messages.def')
    return probs, hashes, fams


def tables(parsed):
    msgs, fams, kinds, feats, _ = parsed
    fam_title = {f['name']: f['title'] for f in fams}
    out = [BEGIN, '', '| Id | Type | Ch | Sent by | Class | Handled by | Family | Contents |', '|---|---|---|---|---|---|---|---|']
    for m in msgs:
        recv = {'Both': '', 'Host': ' (host)', 'Client': ' (guest)'}[m['recv']]
        route = ('Session (net)' if m['route'] == 'None' else m['route']) + recv
        what = m['what'].replace('|', '/')
        out.append(f'| {m["id"]} | `{m["name"]}` | {m["chan"]} | {SENDER[m["dir"]]} | {m["cls"]} | {route} | '
                   f'{m["family"]} | {what} |')
    out += ['', '| Family | Id | Rev | Used in | Covers |', '|---|---|---|---|---|']
    for f in fams:
        stages = ', '.join(STAGES[s] for s in f['stages'])
        covers = ', '.join(f'`{m["name"]}`' for m in msgs if m['family'] == f['name'])
        out.append(f'| {f["name"]} ({fam_title[f["name"]]}) | {f["id"]} | {f["rev"]}.{f["minor"]} | {stages} | {covers} |')
    out += ['', '| `MSG_SPACE` kind | Feature | Name | Sent by |', '|---|---|---|---|']
    for k in kinds:
        out.append(f'| {k["id"]} | {k["feature"]} | `K_{k["name"]}` | {SENDER[k["dir"]]} |')
    out += ['', 'Feature ranges: ' + ', '.join(f'{f["name"]} {f["lo"]}..{f["hi"]}' for f in feats) +
            f'; {feats[-1]["hi"] + 1}..255 free.' if feats else '', '', END]
    return out


def docs_problems(root, parsed):
    text = read(root, DOCS)
    if BEGIN not in text or END not in text:
        return [f'{DOCS}: no manifest tables (run tools/msg_manifest.py docs)']
    a, b = text.index(BEGIN), text.index(END) + len(END)
    if text[a:b] != '\n'.join(tables(parsed)):
        return [f'{DOCS}: the manifest tables differ from messages.def / space_kinds.def (run tools/msg_manifest.py docs)']
    return []


def write_docs(root, parsed):
    path = os.path.join(root, DOCS)
    text = open(path, encoding='utf-8').read()
    gen = '\n'.join(tables(parsed))
    if BEGIN in text and END in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        text = text[:a] + gen + text[b:]
    else:
        raise SystemExit(f'{DOCS}: put the two markers where the tables go:\n{BEGIN}\n{END}')
    open(path, 'w', encoding='utf-8').write(text)


def check(root=ROOT, quiet=False):
    parsed = parse(root)
    probs, _, fams = lock_problems(root, parsed)
    probs += docs_problems(root, parsed)
    for p in probs:
        print('msg_manifest: ' + p)
    if not probs and not quiet:
        print(f'msg_manifest: {len(parsed[0])} types, {len(parsed[2])} space kinds, {len(fams)} families locked, '
              f'docs tables current')
    return 1 if probs else 0


def lock(root=ROOT, rebase=None, reason=''):
    parsed = parse(root)
    if parsed[4]:
        for p in parsed[4]:
            print('msg_manifest: ' + p)
        return 1
    _, hashes, fams = lock_problems(root, parsed)
    old = read_lock(root)
    refused, notes = [], []
    for f in fams:
        n = f['name']
        if n in old and (f['rev'], f['minor']) == old[n][:2] and old[n][2] != hashes[n]:
            if n == rebase and reason.strip():
                notes.append(f'# rebased {n}: {reason.strip()}')
            else:
                refused.append(n)
    if refused:
        print('msg_manifest: not locked: ' + ', '.join(refused) + ' changed without a bumped rev / minor (bump it in '
              'net/messages.def, or `lock --rebase FAMILY "reason"` when the bytes on the wire stay the same)')
        return 1
    write_lock(root, fams, hashes, notes)
    print(f'msg_manifest: {LOCK} written ({len(fams)} families)')
    return 0


def self_test():
    bad = 0
    with tempfile.TemporaryDirectory() as d:
        # every family's wire files too (C6's wire/*.h), else they hash as missing and the copy is not the tree
        wire = sorted({f'mods/coop/{f}' for fam in parse(ROOT)[1] for f in fam['files']})
        for rel in (f'{NET}/messages.def', f'{NET}/space_kinds.def', f'{NET}/protocol.h', LOCK, DOCS, *wire):
            os.makedirs(os.path.dirname(os.path.join(d, rel)), exist_ok=True)
            shutil.copy(os.path.join(ROOT, rel), os.path.join(d, rel))

        def expect(ok, what):
            nonlocal bad
            got = check(d, quiet=True) == 0
            print(f'  {"ok  " if got == ok else "BAD "} {what}: check {"passes" if got else "fails"}')
            bad += got != ok

        def edit(rel, a, b):
            p = os.path.join(d, rel)
            t = open(p, encoding='utf-8').read()
            assert a in t, a
            open(p, 'w', encoding='utf-8').write(t.replace(a, b, 1))

        expect(True, 'the tree as it is')
        edit(f'{NET}/messages.def', 'MSG(56, FIELDS,       U,', 'MSG(56, FIELDS,       R,')
        expect(False, 'a channel changed, no bump')
        print('  ' + ('ok   lock refuses it' if lock(d) == 1 else 'BAD  lock wrote it'))
        npc = re.search(r'FAMILY\(npc,\s+4, 1, (\d+),', open(os.path.join(d, NET, 'messages.def'), encoding='utf-8').read())
        edit(f'{NET}/messages.def', npc.group(0), npc.group(0).replace(f', {npc.group(1)},', f', {int(npc.group(1)) + 1},'))
        write_docs(d, parse(d))
        expect(False, 'bumped, not locked')
        lock(d)
        expect(True, 'bumped and locked')
        edit(f'{NET}/space_kinds.def', 'KIND(81, planets,   SPICE_TAKEN,   Guest)', 'KIND(81, planets,   SPICE_TAKEN,   Any)')
        write_docs(d, parse(d))
        expect(False, 'a space kind direction changed, no bump')
        lock(d, 'space', 'self-test')
        expect(True, 'rebased with a reason')
        edit(f'{NET}/protocol.h', '// SporeCoop wire protocol', '// SporeCoop wire protocol (a comment edit)')
        expect(True, 'a comment of a wire file changed')
        edit(f'{NET}/protocol.h', 'REJ_KICKED = 5,', 'REJ_KICKED = 5, REJ_OTHER = 6,')
        expect(False, 'the code of a wire file changed, no bump')
        edit(DOCS, '| `HELLO` |', '| `HELLO ` |')
        expect(False, 'a docs table edited by hand')
    print('msg_manifest self-test: ' + ('OK' if not bad else f'{bad} FAILED'))
    return 1 if bad else 0


def main(argv):
    if argv[:1] == ['--self-test']:
        return self_test()
    if argv[:1] == ['check']:
        return check()
    if argv[:1] == ['docs']:
        parsed = parse(ROOT)
        write_docs(ROOT, parsed)
        print(f'msg_manifest: {DOCS} tables written')
        return 0
    if argv[:1] == ['lock']:
        if argv[1:2] == ['--rebase'] and len(argv) >= 4:
            return lock(ROOT, argv[2], ' '.join(argv[3:]))
        return lock(ROOT)
    print(__doc__)
    return 2


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
